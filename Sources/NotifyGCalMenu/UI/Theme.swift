import SwiftUI

/**
 * The Aether Utility design system's accent colors. Kept as fixed values rather than
 * semantic/adaptive colors: these are brand accents for icon badges and highlights,
 * not text or surface colors, so they intentionally stay constant across appearances.
 */
enum Theme {
    static let primary = Color(red: 0 / 255, green: 122 / 255, blue: 255 / 255)
    static let primaryTint = Color(red: 225 / 255, green: 245 / 255, blue: 254 / 255)
}
